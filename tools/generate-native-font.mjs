// The chart lettering (Departure Mono, SIL OFL 1.1) as C data for the
// native renderer: digits, capitals, the degree, minus and percent signs,
// run-length rows as in the browser.
import {writeFileSync} from 'node:fs';
import departure from '../data/departure-font.json' with {type:'json'};
const font=departure.regular,chars='0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ °-%',runs=[],glyphs=[];
for(const c of chars){const g=font[c];glyphs.push(`{${g.a},${g.l},${g.t},${runs.length},${g.r.length}}`);for(const [x,y,n] of g.r)runs.push(`{${x},${y},${n}}`);}
const head=`// Generated by tools/generate-native-font.mjs from data/departure-font.json.
// Departure Mono by Helena Zhang, SIL OFL 1.1.
`;
writeFileSync('native/src/c/departure_font.h',head+`#pragma once
#include <stdint.h>
typedef struct {uint8_t x,y,n;} EnrRun;
typedef struct {int8_t advance,left,top;uint16_t first,count;} EnrGlyph;
extern const char ENR_FONT_CHARS[${chars.length+1}];
extern const EnrGlyph ENR_FONT_GLYPHS[${chars.length}];
extern const EnrRun ENR_FONT_RUNS[${runs.length}];
`);
writeFileSync('native/src/c/departure_font.c',head+`#include "departure_font.h"
const char ENR_FONT_CHARS[${chars.length+1}]="${chars.replace('°','\\x7f')}";
const EnrGlyph ENR_FONT_GLYPHS[${chars.length}]={${glyphs.join(',')}};
const EnrRun ENR_FONT_RUNS[${runs.length}]={${runs.join(',')}};
`);
console.log(`${chars.length} glyphs, ${runs.length} runs`);
