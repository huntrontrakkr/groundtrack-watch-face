// The chart lettering (Departure Mono, SIL OFL 1.1) as C data for the
// native renderer: digits, capitals, the degree, minus and percent signs,
// run-length rows as in the browser.
import {writeFileSync} from 'node:fs';
import departure from '../data/departure-font.json' with {type:'json'};
const font=departure.regular,chars='0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ °-%',runs=[],glyphs=[],bin=[];
for(const c of chars){const g=font[c];glyphs.push(`{${g.a},${g.l},${g.t},${runs.length},${g.r.length}}`);
  // font.bin's glyph: i8 advance, left, top, a pad byte, u16 first, count.
  bin.push(g.a&255,g.l&255,g.t&255,0,runs.length&255,runs.length>>8,g.r.length&255,g.r.length>>8);
  for(const [x,y,n] of g.r)runs.push(`{${x},${y},${n}}`);}
for(const c of chars)for(const [x,y,n] of font[c].r)bin.push(x,y,n);
const head=`// Generated by tools/generate-native-font.mjs from data/departure-font.json.
// Departure Mono by Helena Zhang, SIL OFL 1.1.
`;
writeFileSync('native/src/c/departure_font.h',head+`#pragma once
#include <stdint.h>
typedef struct {uint8_t x,y,n;} EnrRun;
typedef struct {int8_t advance,left,top;uint16_t first,count;} EnrGlyph;
#define ENR_FONT_GLYPH_COUNT ${chars.length}
#define ENR_FONT_RUN_COUNT ${runs.length}
// native/resources/font.bin: the glyphs (8 bytes each: advance, left, top,
// a pad byte, first and count little-endian), then the runs (3 bytes each),
// as the structs lie in memory.
#define ENR_FONT_BYTES (8*ENR_FONT_GLYPH_COUNT+3*ENR_FONT_RUN_COUNT)
_Static_assert(sizeof(EnrGlyph)==8&&sizeof(EnrRun)==3,"font.bin is the structs as they lie in memory");
extern const char ENR_FONT_CHARS[${chars.length+1}];
// A character's place among them, or -1.
int enr_font_index(char ch);
// The glyphs and runs: on the watch read from font.bin at start
// (enr_font_load: they are not in its size-capped code), elsewhere compiled in.
extern const EnrGlyph *enr_font_glyphs;
extern const EnrRun *enr_font_runs;
#define ENR_FONT_GLYPHS enr_font_glyphs
#define ENR_FONT_RUNS enr_font_runs
// Points the lettering at font.bin's ENR_FONT_BYTES bytes.
void enr_font_load(const uint8_t *bytes);
`);
writeFileSync('native/src/c/departure_font.c',head+`#include "departure_font.h"
const char ENR_FONT_CHARS[${chars.length+1}]="${chars.replace('°','\\x7f')}";
void enr_font_load(const uint8_t *bytes){enr_font_glyphs=(const EnrGlyph *)bytes;enr_font_runs=(const EnrRun *)(bytes+8*ENR_FONT_GLYPH_COUNT);}
#ifdef PBL_SDK_3
const EnrGlyph *enr_font_glyphs;
const EnrRun *enr_font_runs;
#else
static const EnrGlyph GLYPHS[${chars.length}]={${glyphs.join(',')}};
static const EnrRun RUNS[${runs.length}]={${runs.join(',')}};
const EnrGlyph *enr_font_glyphs=GLYPHS;
const EnrRun *enr_font_runs=RUNS;
#endif

int enr_font_index(char ch){if(ch)for(int k=0;ENR_FONT_CHARS[k];k++)if(ENR_FONT_CHARS[k]==ch)return k;return -1;}
`);
writeFileSync('native/resources/font.bin',Uint8Array.from(bin));
console.log(`${chars.length} glyphs, ${runs.length} runs; native/resources/font.bin: ${bin.length} bytes`);
