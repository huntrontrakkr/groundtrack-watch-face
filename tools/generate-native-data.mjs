// The chart's data as C, for the watch's own renderer (native/src/c/chart.c):
// the plates, the tracking stations, the relief height table and the hour
// figures, taken from the JavaScript so both sides use the same numbers to
// the bit. Doubles are written as their exact hexadecimal values.
//
//   node tools/generate-native-data.mjs
import {writeFileSync,mkdirSync} from 'node:fs';
import {PLATES,CONTOURS,SHELF,SPAN,W,H} from '../src/enroute-render.js';
import {TRACK_Y} from '../src/chart-render.js';
import {reliefMeters} from '../src/relief.js';
import network from '../data/tracking-stations.json' with {type:'json'};
import numerals from '../data/enroute-font.json' with {type:'json'};

const hexDouble=v=>{if(v===Infinity)return 'INFINITY';if(v===-Infinity)return '-INFINITY';const d=new DataView(new ArrayBuffer(8));d.setFloat64(0,v);const b=d.getBigUint64(0);
  // C99 hex float: exact.
  if(v===0)return Object.is(v,-0)?'-0.0':'0.0';
  const sign=b>>63n?'-':'',exp=Number((b>>52n)&0x7ffn),mant=b&0xfffffffffffffn;
  return exp===0?`${sign}0x0.${mant.toString(16).padStart(13,'0')}p-1022`:`${sign}0x1.${mant.toString(16).padStart(13,'0')}p${exp-1023}`;};
const hexFloat=v=>{const f=new DataView(new ArrayBuffer(4));f.setFloat32(0,v);return `0x${f.getUint32(0).toString(16).padStart(8,'0')}u`;};
const g8=c=>c?0xC0|(c[0]/85)<<4|(c[1]/85)<<2|c[2]/85:0;

const keys=['enroute','sectional','plotboard','hypsometric','red','crt','sunlight'];
if(keys.join()!==Object.keys(PLATES).join())throw new Error('Plate order changed: update native/src/c/chart.h');
const inks=['water','land','coast','contour','shelf','grid','route','ink','mark'];
const plates=keys.map(k=>{
  const p=PLATES[k],flags=[p.night==='zones'?'PLATE_ZONES':0,p.scan?'PLATE_SCAN':0,p.terminator?'PLATE_TERMINATOR':0,p.nightDots?'PLATE_NIGHT_DOTS':0,p.mono?'PLATE_MONO':0,p.dots?'PLATE_DOTS':0,p.waterline?'PLATE_WATERLINE':0].filter(Boolean).join('|')||'0';
  const tints=p.tints||[],depths=p.depths||[];
  return `  {/* ${k} */ ${flags},{${inks.map(i=>`{${p[i].map(g8).join(',')}}`).join(',')}},${g8(p.space)},${g8(p.spaceInk)},${g8(p.screen)},${g8(p.waterline)},${g8(p.terminator)},${g8(p.nightDots)},\n`+
    `    ${tints.length},{${[0,1,2,3,4].map(i=>g8(tints[i]?.[1])).join(',')}},{${[0,1,2,3,4].map(i=>hexDouble(tints[i]?.[0]??0)).join(',')}},${depths.length},{${[0,1].map(i=>g8(depths[i]?.[1])).join(',')}},{${[0,1].map(i=>hexDouble(depths[i]?.[0]??0)).join(',')}}}`;
});
const stations=network.stations.map(s=>`  {"${s.code}",${hexDouble(s.lat)},${hexDouble(s.lon)}}`);
// The relief heights exactly as decodeRelief's Float32Array holds them.
const meters=Float32Array.from({length:256},(_,c)=>reliefMeters(c));
// The figures: per size, each digit's width, height and rows as bits.
const sizes=[20,28,40,72,80],glyphs=[],bits=[];
for(const size of sizes)for(const c of '0123456789'){
  const g=numerals.sizes[size][c],first=bits.length;
  for(const row of g.rows){for(let x=0;x<g.width;x+=8){let b=0;for(let k=0;k<8;k++)if(row[x+k]==='#')b|=128>>k;bits.push(b);}}
  glyphs.push(`{${g.width},${g.height},${first}}`);
}

mkdirSync('native/src/c/generated',{recursive:true});
writeFileSync('native/src/c/generated/chart_data.h',`// Generated by tools/generate-native-data.mjs from the JavaScript's plates,
// data/tracking-stations.json, the relief decoding and data/enroute-font.json
// (Jost by Indestructible Type, SIL OFL 1.1). Do not edit.
#pragma once
#include <math.h>
#include "../chart.h"

#define CHART_W ${W}
#define CHART_H ${H}
#define CHART_SPAN ${SPAN}
#define CHART_TRACK_Y ${TRACK_Y}
#define CHART_SHELF ${SHELF}
static const int CHART_CONTOURS[${CONTOURS.length}]={${CONTOURS.join(',')}};

static const Plate PLATES[${plates.length}]={
${plates.join(',\n')}
};

static const Station STATIONS[${stations.length}]={
${stations.join(',\n')}
};

// Relief codes to metres, as float bits.
static const uint32_t RELIEF_METERS_BITS[256]={${Array.from(meters,hexFloat).join(',')}};

// Jost figures at ${sizes.join(', ')} px: per size ten digits, each {width, height,
// first byte in native/resources/figures.bin}; rows are packed MSB first,
// (width+7)/8 bytes a row. The bits are a resource, loaded a size at a time.
static const uint8_t FIGURE_SIZES[${sizes.length}]={${sizes.join(',')}};
static const FigureGlyph FIGURE_GLYPHS[${glyphs.length}]={${glyphs.join(',')}};
#define FIGURE_BYTES ${bits.length}
`);
mkdirSync('native/resources',{recursive:true});
writeFileSync('native/resources/figures.bin',Uint8Array.from(bits));
console.log(`native/src/c/generated/chart_data.h: ${plates.length} plates, ${stations.length} stations; native/resources/figures.bin: ${bits.length} bytes`);
